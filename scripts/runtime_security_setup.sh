# ── Interactive mode ───────────────────────────────────────────────
interactive_mode() {
    echo -e "${C_INFO}╔══════════════════════════════════════════╗${C_RST}"
    echo -e "${C_INFO}║  Runtime Security Setup Wizard            ║${C_RST}"
    echo -e "${C_INFO}║  $APP_NAME $APP_VER                        ║${C_RST}"
    echo -e "${C_INFO}╚══════════════════════════════════════════╝${C_RST}"
    echo ""

    check_kernel_version || true
    check_btf || true
    echo ""

    echo -e "${C_INFO}Runtime security solution comparison:${C_RST}"
    echo ""
    echo -e "  ${C_WARN}1.${C_RST} Falco — detect+alert (CNCF graduated, 100+ built-in rules)"
    echo -e "  ${C_WARN}2.${C_RST} Tetragon — detect+enforce (eBPF real-time blocking)"
    echo -e "  ${C_WARN}3.${C_RST} Deploy both (Falco alert + Tetragon block = defense in depth)"
    echo -e "  ${C_WARN}4.${C_RST} Audit current status only (no config generated)"
    echo -e "  ${C_WARN}5.${C_RST} View detection rules"
    echo -e "  ${C_WARN}0.${C_RST} Exit"
    echo ""
    local pick
    read -r -p "Select [0-5]: " pick
    case $pick in
        1) generate_falco_config ;;
        2) generate_tetragon_config ;;
        3) generate_falco_config; echo ""; generate_tetragon_config ;;
        4) audit_runtime_security ;;
        5) list_rules ;;
        0) echo "Exit"; exit 0 ;;
        *) echo -e "${C_FAIL}Invalid input${C_RST}"; exit 1 ;;
    esac
}

# ── Main flow ───────────────────────────────────────────────────
main() {
    parse_args "$@"

    case "$MODE" in
        falco)
            check_kernel_version || true
            generate_falco_config
            ;;
        tetragon)
            check_kernel_version || true
            generate_tetragon_config
            ;;
        audit)
            audit_runtime_security || true
            ;;
        rules)
            list_rules
            ;;
        interactive)
            interactive_mode || true
            ;;
        *)
            echo "Unknown mode: $MODE"; exit 1
            ;;
    esac
    return 0
}

main "$@"
